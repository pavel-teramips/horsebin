#!/bin/sh
# Installs HorseBin as a systemd service behind Caddy (Linux, run as root from the repo checkout).
#
#   sudo DOMAINS="paste.example.com" ABUSE="abuse@example.com" sh setup.sh
#
# DOMAINS  host names for the Caddy site block, comma-separated; the first is the one printed in links
# ABUSE    optional abuse contact shown on /terms
# Runs server.py from this directory as the invoking user ($SUDO_USER), data in ~/horsebin.
# Writes /etc/systemd/system/horsebin.service and $CADDY_SITE (your Caddyfile must
# `import sites-enabled/*.caddy`, or paste the site block into it yourself).
set -eu

: "${DOMAINS:?set DOMAINS, e.g. DOMAINS=paste.example.com}"
ABUSE="${ABUSE:-}"
RUN_USER="${RUN_USER:-${SUDO_USER:?run with sudo from your own account, or set RUN_USER}}"
RUN_HOME="$(getent passwd "$RUN_USER" | cut -d: -f6)"
APP_DIR="$(cd "$(dirname "$0")" && pwd)"
DATA_DIR="${DATA_DIR:-$RUN_HOME/horsebin}"
PORT="${PORT:-3050}"
SITE="$(echo "$DOMAINS" | cut -d, -f1 | tr -d ' ')"
CADDY_SITE="${CADDY_SITE:-/etc/caddy/sites-enabled/horsebin.caddy}"

install -d -o "$RUN_USER" -g "$(id -gn "$RUN_USER")" -m 0700 "$DATA_DIR"

cat > /etc/systemd/system/horsebin.service <<EOF
[Unit]
Description=HorseBin: pastebin with 3-word URLs ($SITE)
After=network-online.target

[Service]
User=$RUN_USER
WorkingDirectory=$APP_DIR
ExecStart=/usr/bin/python3 $APP_DIR/server.py
Restart=on-failure
RestartSec=5
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=read-only
ReadWritePaths=$DATA_DIR
PrivateTmp=yes
Environment=HORSEBIN_DIR=$DATA_DIR
Environment=HORSEBIN_PORT=$PORT
Environment=HORSEBIN_SITE=$SITE
Environment=HORSEBIN_MAX_MB=25
Environment=HORSEBIN_MAX_TOTAL_MB=2048
Environment=HORSEBIN_MAX_PER_IP_MB=200
Environment=HORSEBIN_COMPACT_MB=1536
Environment=HORSEBIN_ABUSE=$ABUSE

[Install]
WantedBy=multi-user.target
EOF

install -d "$(dirname "$CADDY_SITE")"
cat > "$CADDY_SITE" <<EOF
# HorseBin, public pastebin with 3-word URLs. Deliberately no auth. Generated by setup.sh.
$DOMAINS {
    encode gzip zstd
    request_body {
        max_size 27MB
    }
    reverse_proxy 127.0.0.1:$PORT

    header X-Robots-Tag "noindex, nofollow"

    log {
        output file /var/log/caddy/horsebin.log {
            roll_size 10mb
            roll_keep 5
        }
    }
}
EOF

systemctl daemon-reload
systemctl enable --now horsebin.service
systemctl restart horsebin.service
caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile
systemctl reload caddy
sleep 2
curl -s -o /dev/null -w 'horsebin local: %{http_code}\n' "http://127.0.0.1:$PORT/"
curl -s -o /dev/null -w "horsebin public: %{http_code}\n" "https://$SITE/" || echo "public check failed (cert may still be issuing; retry in a minute)"
